namespace BengaliKeyboard.Core.Enums;

/// <summary>
/// Visual theme preference for the keyboard and companion windows.
/// </summary>
public enum AppTheme
{
    /// <summary>
    /// Ridmik signature dark slate theme (Default).
    /// </summary>
    Dark = 0,

    /// <summary>
    /// Windows 11 daylight theme.
    /// </summary>
    Light = 1,

    /// <summary>
    /// Automatically follows the Windows OS app theme setting.
    /// </summary>
    System = 2
}
